const TEXT = { zh, en };

export function currentLocale() {
	return document.documentElement.dataset.locale === "en" ? "en" : "zh";
}

/** Unknown keys return the key itself — better a visible defect than invented copy. */
export function t(key, vars) {
	let value = TEXT[currentLocale()][key] ?? TEXT.en[key];
	if (value === undefined) return String(key);
	if (!vars) return value;
	for (const [name, replacement] of Object.entries(vars)) {
		value = value.split(`{${name}}`).join(String(replacement));
	}
	return value;
}

export function hasKey(key) {
	return TEXT.en[key] !== undefined;
}

export function setLocale(locale) {
	const next = locale === "en" ? "en" : "zh";
	document.documentElement.dataset.locale = next;
	document.documentElement.lang = next === "zh" ? "zh-CN" : "en";
	try {
		localStorage.setItem("pi-insights-locale", next);
	} catch {}
}

/** Fills every declarative slot in index.html so markup carries no copy. */
export function applyStaticText(root = document) {
	for (const element of root.querySelectorAll("[data-text]")) {
		element.textContent = t(element.dataset.text);
	}
	for (const element of root.querySelectorAll("[data-title]")) {
		element.title = t(element.dataset.title);
	}
	for (const element of root.querySelectorAll("[data-label]")) {
		element.setAttribute("aria-label", t(element.dataset.label));
	}
	for (const element of root.querySelectorAll("[data-placeholder]")) {
		element.placeholder = t(element.dataset.placeholder);
	}
}
