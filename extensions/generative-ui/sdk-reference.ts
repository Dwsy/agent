// ── Generate the Canvas SDK API reference ─────────────────────────────────
// The canvas SDK ships as a source string (canvas-sdk-source.ts), so it has no
// .d.ts to grep. This generator turns its actual exports into the closed API
// reference the model reads before writing unfamiliar TSX. Run:
//   bun sdk-reference.ts
// The checked-in reference is pinned by sdk-reference.test.mjs.

import { fileURLToPath } from "node:url";
import { CANVAS_SDK_SOURCE } from "./canvas-sdk-source.js";

interface SdkFunction {
  name: string;
  args: string;
}

const COMPONENT_NOTES: Record<string, string> = {
  H1: "Forwards all props to the shared Heading primitive.",
  H2: "Forwards all props to the shared Heading primitive.",
  H3: "Forwards all props to the shared Heading primitive.",
  DataTable: "Legacy alias for the column/row table shape; prefer `Table`.",
  CanvasChevron: "Internal disclosure glyph; exported for reuse.",
  Heatmap: "A matrix: `values[row][column]`. A row of day squares across a year is not a heatmap.",
  Scatter: "Renders its own legend when points carry more than one `series`.",
  PieChart: "Renders its own legend; do not add a second one.",
  BarChart: "Renders its own legend when there are 2+ series.",
  LineChart: "Renders its own legend when there are 2+ series.",
};

function parse(source: string) {
  const constants: { name: string; value: string }[] = [];
  const functions: SdkFunction[] = [];
  for (const line of source.split("\n")) {
    const constant = /^export const (\w+)\s*=\s*(.*)$/.exec(line);
    if (constant) {
      constants.push({ name: constant[1], value: constant[2].replace(/;\s*$/, "") });
      continue;
    }
    const fn = /^export function (\w+)\(([^)]*)\)\s*\{/.exec(line);
    if (!fn) continue;
    const args = fn[2].trim();
    functions.push({ name: fn[1], args });
  }
  return { constants, functions };
}

function describeConstant(value: string): string {
  if (value.startsWith("{")) return "object literal";
  if (value.startsWith("[")) return "array";
  if (value.includes("tokensFromPalette(")) return "derived theme tokens";
  if (/^\w+$/.test(value)) return "alias of `" + value + "`";
  return value.slice(0, 60);
}

function signature(fn: SdkFunction): string {
  return "`" + fn.name + "(" + fn.args + ")`";
}

/** Render the complete, deterministic SDK reference from the SDK source. */
export function renderSdkReference(source: string): string {
  const { constants, functions } = parse(source);
  const components = functions.filter((fn) => /^[A-Z]/.test(fn.name));
  const apis = functions.filter((fn) => !/^[A-Z]/.test(fn.name));

  const out: string[] = [
    "# @gen-ui/canvas SDK reference",
    "",
    "> Generated by `bun sdk-reference.ts` from `canvas-sdk-source.ts`. Do not edit by hand.",
    "> This is the **closed export list**: importing a name absent from this file fails the",
    "> canvas esbuild compile. Prop names and defaults come from the destructured signatures;",
    "> the SDK source is untyped, so there are no TypeScript types to quote.",
    "",
    "## Import contract",
    "",
    "- Allowed imports: `react`, `react-dom`, `react-dom/client`, `@gen-ui/canvas`.",
    "- One TSX file, default-export the top-level component; data stays inline.",
    "- No `fetch` / `XMLHttpRequest` / `WebSocket`; no external resources outside the host allowlist.",
    "- SDK components take `style`, not `className`; put Tailwind utilities on plain DOM elements.",
    "- Colors come from `useHostTheme()` tokens or host CSS variables, never a hardcoded palette.",
    "",
    "## Tokens & constants (" + constants.length + ")",
    "",
    "| name | value |",
    "|---|---|",
  ];
  for (const constant of constants) {
    out.push("| `" + constant.name + "` | " + describeConstant(constant.value) + " |");
  }

  out.push("", "## Hooks, helpers & host bridges (" + apis.length + ")", "", "| name | signature |", "|---|---|");
  for (const fn of apis) out.push("| `" + fn.name + "` | " + signature(fn) + " |");

  out.push("", "## Components (" + components.length + ")", "", "| component | signature (prop names + defaults) |", "|---|---|");
  for (const fn of components) out.push("| `" + fn.name + "` | " + signature(fn) + " |");

  out.push("", "## Component notes", "");
  for (const [name, note] of Object.entries(COMPONENT_NOTES)) {
    if (components.some((fn) => fn.name === name)) out.push("- `" + name + "`: " + note);
  }

  out.push(
    "## Conventions",
    "",
    "- `style` is a React style object merged with `mergeStyle(base, override)`.",
    "- Charts render their own legend when there are 2+ series; `PieChart` always does.",
    "- `useCanvasState(key, defaultValue)` persists JSON per canvas; `useHostTheme()` follows the host light/dark bridge.",
    "- `sendToAgent` / `sendPrompt` / `sendAnnotation` are Pi host bridges, not Cursor IDE actions.",
    "",
  );
  return out.join("\n");
}

if (import.meta.main) {
  const { writeFileSync } = await import("node:fs");
  const target = new URL("./skills/generative-ui/references/sdk.md", import.meta.url);
  writeFileSync(target, renderSdkReference(CANVAS_SDK_SOURCE), "utf8");
  console.log("wrote " + fileURLToPath(target));
}
